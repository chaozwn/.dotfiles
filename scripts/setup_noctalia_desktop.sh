#!/usr/bin/env bash
# Machine-local pieces of the Noctalia desktop. Safe to re-run.
# Packages come from scripts/bootstrap-fedora.sh. Shared look is noctalia/appearance.toml.

set -euo pipefail

if [ "$(uname)" != "Linux" ]; then
  exit 0
fi

config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/noctalia"
mkdir -p "$config_dir"

wallpaper_toml="$config_dir/wallpaper.toml"
if [ ! -e "$wallpaper_toml" ]; then
  pictures="${XDG_PICTURES_DIR:-$HOME/图片}"
  if [ -f "${XDG_CONFIG_HOME:-$HOME/.config}/user-dirs.dirs" ]; then
    # shellcheck disable=SC1090
    pictures="$(. "${XDG_CONFIG_HOME:-$HOME/.config}/user-dirs.dirs" && printf '%s' "${XDG_PICTURES_DIR:-$pictures}")"
  fi
  cat >"$wallpaper_toml" <<EOF
# Generated by scripts/setup_noctalia_desktop.sh. Not in git.
[wallpaper]
directory = "${pictures}/wallpaper"
EOF
  echo "==> Wrote $wallpaper_toml"
fi

if command -v qt6ct >/dev/null 2>&1 || [ -d "$HOME/.config/qt6ct" ]; then
  mkdir -p "$HOME/.config/qt6ct/colors"
  qt6ct_conf="$HOME/.config/qt6ct/qt6ct.conf"
  palette="$HOME/.config/qt6ct/colors/noctalia.conf"
  if [ ! -f "$qt6ct_conf" ]; then
    cat >"$qt6ct_conf" <<EOF
[Appearance]
color_scheme_path=${palette}
custom_palette=true
icon_theme=Adwaita
standard_dialogs=default
style=Fusion
EOF
    echo "==> Wrote $qt6ct_conf"
  elif ! grep -q 'colors/noctalia.conf' "$qt6ct_conf"; then
    echo "ℹ️  $qt6ct_conf exists and does not point at Noctalia; left it unchanged."
  fi
fi

if command -v noctalia >/dev/null 2>&1; then
  if noctalia msg templates-apply >/dev/null 2>&1; then
    echo "==> Applied Noctalia theme templates."
  else
    echo "ℹ️  Noctalia is not running. Templates apply on the next login."
  fi
fi
